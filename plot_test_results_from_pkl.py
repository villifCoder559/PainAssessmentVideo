def parse_args() -> argparse.Namespace:
  """
  Parse command-line arguments.

  Returns:
    Namespace with attributes:
      pkl (str): path to the pkl file.
      scale_predictions (bool): if True, linearly scale predictions by
        N_test_classes / N_train_classes before plotting.
  """
  parser = argparse.ArgumentParser(
    description='Plot test results from a pkl file.'
  )
  parser.add_argument(
    '--pkl', required=True,
    help='Path to the pkl file (must contain a "results" key).'
  )
  parser.add_argument(
    '--scale_predictions', action='store_true',
    help=(
      'Scale predictions linearly by N_test_classes / N_train_classes. '
      'N_train is read from the training CSV in config_model, '
      'N_test from the CSV referenced in the pkl. '
      'All prediction-based plots are recomputed from the scaled values.'
    ),
  )
  return parser.parse_args()


