def _concordance_ccc(y_true: np.ndarray, y_pred: np.ndarray) -> float:
  """
  Concordance Correlation Coefficient.

  CCC = 2·cov(y_true, y_pred) / (var(y_true) + var(y_pred) + (mean_true − mean_pred)²)

  Args:
    y_true: Ground-truth values. Shape: (N,).
    y_pred: Predicted values.   Shape: (N,).

  Returns:
    CCC float. Returns nan if denominator is zero.
  """
  y_true = np.asarray(y_true, dtype=np.float64)
  y_pred = np.asarray(y_pred, dtype=np.float64)
  mu_t, mu_p = y_true.mean(), y_pred.mean()
  var_t = y_true.var(ddof=0)
  var_p = y_pred.var(ddof=0)
  cov   = np.mean((y_true - mu_t) * (y_pred - mu_p))
  denom = var_t + var_p + (mu_t - mu_p) ** 2
  if denom == 0:
    return 1.0 if np.allclose(y_true, y_pred) else np.nan
  return float(2.0 * cov / denom)


def _intraclass_icc(y_true: np.ndarray, y_pred: np.ndarray) -> float:
  """
  Intraclass Correlation Coefficient ICC(2,1) — two-way random, single measures.

  Args:
    y_true: Ground-truth values. Shape: (N,).
    y_pred: Predicted values.   Shape: (N,).

  Returns:
    ICC float. Returns nan if denominator is zero.
  """
  arr  = np.column_stack([y_true, y_pred]).astype(np.float64)
  n, k = arr.shape   # k == 2

  mean_subj  = arr.mean(axis=1)
  mean_rater = arr.mean(axis=0)
  grand_mean = arr.mean()

  ss_total   = np.sum((arr - grand_mean) ** 2)
  ss_between = k * np.sum((mean_subj - grand_mean) ** 2)
  ss_raters  = n * np.sum((mean_rater - grand_mean) ** 2)
  ss_residual = ss_total - ss_between - ss_raters

  msr = ss_between / (n - 1)
  msc = ss_raters / (k - 1)
  mse = ss_residual / ((n - 1) * (k - 1))

  denom = msr + (k - 1) * mse + (k * (msc - mse) / n)
  if denom == 0:
    return np.nan
  return float((msr - mse) / denom)


def recompute_scaled(
  sample_df: pd.DataFrame,
  scale: float,
  n_classes: int,
  unique_subjects: list,
) -> dict:
  """
  Recompute all prediction-based metrics after scaling predictions by `scale`.

  Predictions are clipped and rounded to integer class labels for
  classification metrics; the continuous scaled values are used for
  regression metrics (L1, RMSE, Pearson, CCC, ICC).

  Args:
    sample_df:       DataFrame with columns [pred, true_class, subject_id].
                     Shape: (N_samples,).
    scale:           Multiplicative scale factor applied to predictions.
    n_classes:       Number of test classes (confusion matrix size).
    unique_subjects: Ordered list of unique subject IDs (same order as
                     results['test_unique_subject_ids']).

  Returns:
    Dict with keys matching the relevant subset of the results dict:
      cm, test_loss_per_class, test_loss_per_subject,
      test_accuracy_per_class, test_accuracy_per_subject,
      dict_precision_recall, test_l1_error, test_rmse,
      test_pearson_correlation, test_CCC, test_ICC,
      test_accuracy, test_macro_precision, test_loss.
  """
  scaled_preds = (sample_df['pred'].values * scale).astype(np.float64)
  trues        = sample_df['true_class'].values.astype(np.float64)
  pred_classes = np.clip(np.round(scaled_preds).astype(int), 0, n_classes - 1)
  subject_ids  = sample_df['subject_id'].values

  # Confusion matrix
  labels = list(range(n_classes))
  cm = sk_confusion_matrix(trues.astype(int), pred_classes, labels=labels)

  # Per-class metrics
  loss_per_class = np.zeros(n_classes, dtype=np.float64)
  acc_per_class  = np.zeros(n_classes, dtype=np.float64)
  for c in labels:
    mask = trues.astype(int) == c
    if mask.sum() > 0:
      loss_per_class[c] = float(np.mean(np.abs(scaled_preds[mask] - trues[mask])))
      acc_per_class[c]  = float(np.mean(pred_classes[mask] == c))

  # Per-subject metrics (preserve order of unique_subjects)
  n_subjects       = len(unique_subjects)
  loss_per_subject = np.zeros(n_subjects, dtype=np.float64)
  acc_per_subject  = np.zeros(n_subjects, dtype=np.float64)
  for i, s in enumerate(unique_subjects):
    mask = subject_ids == int(s)
    if mask.sum() > 0:
      loss_per_subject[i] = float(np.mean(np.abs(scaled_preds[mask] - trues[mask])))
      acc_per_subject[i]  = float(np.mean(pred_classes[mask] == trues[mask].astype(int)))

  # Precision / recall
  prec_per_class = precision_score(
    trues.astype(int), pred_classes, labels=labels, average=None, zero_division=0
  )
  rec_per_class  = recall_score(
    trues.astype(int), pred_classes, labels=labels, average=None, zero_division=0
  )
  macro_prec = float(precision_score(
    trues.astype(int), pred_classes, average='macro', zero_division=0
  ))
  macro_rec  = float(recall_score(
    trues.astype(int), pred_classes, average='macro', zero_division=0
  ))

  # Scalar regression metrics
  l1   = float(np.mean(np.abs(scaled_preds - trues)))
  rmse = float(np.sqrt(np.mean((scaled_preds - trues) ** 2)))
  r, p = stats.pearsonr(trues, scaled_preds)
  ccc  = _concordance_ccc(trues, scaled_preds)
  icc  = _intraclass_icc(trues, scaled_preds)
  acc  = float(np.mean(pred_classes == trues.astype(int)))

  return {
    'cm': cm,
    'test_loss_per_class':   loss_per_class,
    'test_loss_per_subject': loss_per_subject,
    'test_accuracy_per_class':   acc_per_class,
    'test_accuracy_per_subject': acc_per_subject,
    'dict_precision_recall': {
      'precision_per_class':  prec_per_class,
      'recall_per_class':     rec_per_class,
      'macro_precision':      np.float32(macro_prec),
      'macro_recall':         np.float32(macro_rec),
    },
    'test_l1_error':              l1,
    'test_rmse':                  rmse,
    'test_pearson_correlation':   (float(r), float(p)),
    'test_CCC':                   ccc,
    'test_ICC':                   icc,
    'test_accuracy':              acc,
    'test_macro_precision':       macro_prec,
    'test_loss':                  l1,
    # Internal arrays for the scatter plot (underscore prefix = not a metric key)
    '_preds_arr': scaled_preds,
    '_trues_arr': trues,
  }


