def compute_scale_factor(data: dict) -> float:
  """
  Compute the linear scaling constant N_test / N_train.

  N_train = number of unique class_id values in the training CSV at
            data['config_model']['model_advanced_params']['path_labels'].
  N_test  = number of unique class_id values in the test CSV at
            data['csv_path'] (or data['csv_original_path']).

  Args:
    data: Full pkl dictionary.

  Returns:
    Float scale factor N_test / N_train.

  Raises:
    FileNotFoundError: If the training CSV path cannot be resolved.
    ValueError:        If class counts cannot be determined.
  """
  # --- training CSV ---
  train_csv_path = (
    data.get('config_model', {})
    .get('model_advanced_params', {})
    .get('path_labels')
  )
  if not train_csv_path or not os.path.isfile(train_csv_path):
    raise FileNotFoundError(
      f'Training CSV not found at: {train_csv_path!r}. '
      'Cannot compute scale factor.'
    )
  df_train = pd.read_csv(train_csv_path, sep='\t')
  n_train  = int(df_train['class_id'].nunique())

  # --- test CSV ---
  df_test = _read_csv_safe(data)
  if df_test.empty or 'class_id' not in df_test.columns:
    raise ValueError('Test CSV unavailable or missing class_id column.')
  n_test = int(df_test['class_id'].nunique())

  if n_train == 0:
    raise ValueError('Training CSV has 0 unique classes.')

  scale = n_test / n_train
  print(
    f'Scale factor: {n_test} (test classes) / {n_train} (train classes) = {scale:.4f}'
  )
  return scale


def build_sample_df(data: dict, results: dict) -> pd.DataFrame:
  """
  Build a per-sample DataFrame aligning predictions, ground-truth labels,
  and subject IDs.

  Uses history_test_sample_predictions for predictions and the test CSV
  for ground-truth class_id and subject_id.

  Args:
    data:    Full pkl dictionary.
    results: Results dictionary from the pkl.

  Returns:
    DataFrame with columns [sample_id (int), pred (float),
    true_class (int), subject_id (int)].
  """
  df_csv = _read_csv_safe(data)
  gt_map   = {}
  subj_map = {}
  if not df_csv.empty:
    if 'sample_id' in df_csv.columns and 'class_id' in df_csv.columns:
      gt_map = dict(zip(df_csv['sample_id'].astype(int), df_csv['class_id'].astype(int)))
    if 'sample_id' in df_csv.columns and 'subject_id' in df_csv.columns:
      subj_map = dict(zip(df_csv['sample_id'].astype(int), df_csv['subject_id'].astype(int)))

  hist = results['history_test_sample_predictions']
  rows = []
  for sid in sorted(hist.keys()):
    pred = hist[sid][0]
    if isinstance(pred, torch.Tensor):
      pred = pred.item()
    sid_int    = int(sid)
    true_class = gt_map.get(sid_int)
    subject_id = subj_map.get(sid_int)
    if true_class is not None and subject_id is not None:
      rows.append({
        'sample_id':  sid_int,
        'pred':       float(pred),
        'true_class': int(true_class),
        'subject_id': int(subject_id),
      })

  return pd.DataFrame(rows)


def _raw_errors_by_group(
  sample_df: pd.DataFrame,
  group_col: str,
  ordered_ids: list,
  preds_arr: np.ndarray = None,
) -> list:
  """
  Compute per-sample absolute prediction errors grouped by class or subject.

  Args:
    sample_df:   DataFrame with columns [pred, true_class, subject_id].
                 Shape: (N_samples,).
    group_col:   Column to group by ('true_class' or 'subject_id').
    ordered_ids: Group IDs in display order (aligns with class/subject labels).
    preds_arr:   Optional predictions row-aligned with sample_df (e.g. scaled).
                 If None, uses sample_df['pred'].

  Returns:
    List of 1-D float64 arrays of absolute errors, one per ID in ordered_ids.
    Empty groups produce np.array([np.nan]).
  """
  preds  = preds_arr if preds_arr is not None else sample_df['pred'].values
  errors = np.abs(
    preds.astype(np.float64) - sample_df['true_class'].values.astype(np.float64)
  )
  groups = sample_df[group_col].values

  result = []
  for gid in ordered_ids:
    mask = groups == int(gid)
    result.append(errors[mask].copy() if mask.sum() > 0 else np.array([np.nan]))
  return result


def _preds_by_group(
  sample_df: pd.DataFrame,
  ordered_ids: list,
  preds_arr: np.ndarray = None,
  round_preds: bool = False,
) -> list:
  """
  Collect per-sample predictions grouped by true class.

  Args:
    sample_df:   DataFrame with columns [pred, true_class, subject_id].
                 Shape: (N_samples,).
    ordered_ids: Class IDs in display order (aligns with class_labels).
    preds_arr:   Optional predictions row-aligned with sample_df (e.g. scaled).
                 If None, uses sample_df['pred'].
    round_preds: If True, round predictions to nearest integer before grouping.

  Returns:
    List of 1-D float64 arrays of predictions, one per ID in ordered_ids.
    Empty groups produce np.array([np.nan]).
  """
  preds = (
    preds_arr if preds_arr is not None else sample_df['pred'].values
  ).astype(np.float64)
  if round_preds:
    preds = np.round(preds)
  groups = sample_df['true_class'].values
  result = []
  for gid in ordered_ids:
    mask = groups == int(gid)
    result.append(preds[mask].copy() if mask.sum() > 0 else np.array([np.nan]))
  return result


