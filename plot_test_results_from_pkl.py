def get_class_labels(data: dict) -> list:
  """
  Build a list of class label strings aligned with results['test_unique_y'].

  Reads class_name values from the CSV referenced in data['csv_path']
  (fallback: data['csv_original_path']). CSV is assumed tab-separated with
  columns 'class_id' and 'class_name'. Falls back to integer string labels.

  Args:
    data: Full pkl dictionary.

  Returns:
    List of class label strings sorted by class_id.
  """
  unique_y = _to_numpy(data['results']['test_unique_y'])
  df = _read_csv_safe(data)
  if not df.empty and 'class_id' in df.columns and 'class_name' in df.columns:
    mapping = (
      df[['class_id', 'class_name']]
      .drop_duplicates()
      .sort_values('class_id')
    )
    return [str(row['class_name']) for _, row in mapping.iterrows()]
  return [str(int(v)) for v in unique_y]


def get_subject_labels(results: dict) -> list:
  """
  Build a list of subject label strings from results['test_unique_subject_ids'].

  Args:
    results: The results dictionary from the pkl.

  Returns:
    List of subject ID strings in original order.
  """
  return [str(int(v)) for v in results['test_unique_subject_ids']]


def get_gt_map(data: dict) -> dict:
  """
  Build a sample_id → class_id mapping from the test CSV.

  Args:
    data: Full pkl dictionary.

  Returns:
    Dict mapping sample_id (int) to class_id (int). Empty if CSV unavailable.
  """
  df = _read_csv_safe(data)
  if not df.empty and 'sample_id' in df.columns and 'class_id' in df.columns:
    return dict(zip(df['sample_id'].astype(int), df['class_id'].astype(int)))
  return {}


def _get_csv_class_range(data: dict) -> tuple:
  """
  Return the (min, max) class_id values from the test CSV as floats.

  Args:
    data: Full pkl dictionary.

  Returns:
    Tuple (min_class_id, max_class_id) as floats. Returns (None, None)
    if the CSV is unavailable or lacks a class_id column.
  """
  df = _read_csv_safe(data)
  if not df.empty and 'class_id' in df.columns:
    return float(df['class_id'].min()), float(df['class_id'].max())
  return None, None


def get_confusion_matrix(results: dict) -> np.ndarray:
  """
  Compute the confusion matrix as a numpy array sliced to n_classes × n_classes.

  The torchmetrics object may produce a (n_classes+1, n_classes+1) tensor with
  an extra ignore bucket; this function clips it to the correct size.

  Args:
    results: The results dictionary from the pkl.

  Returns:
    numpy int array of shape (n_classes, n_classes).
  """
  cm = results['test_confusion_matrix'].compute().cpu().numpy()
  n  = len(results['test_unique_y'])
  return cm[:n, :n].astype(int)


def get_model_name(data: dict) -> str:
  """
  Extract the model filename (without extension) from data['model_pth_path'].

  Args:
    data: Full pkl dictionary.

  Returns:
    Model name string, e.g. 'best_model_ep_24'. Returns '' if key absent.
  """
  pth_path = data.get('model_pth_path', '')
  return os.path.splitext(os.path.basename(pth_path))[0]


