def main() -> None:
  """
  Entry point: load pkl, optionally scale predictions, generate all plots.

  With --scale_predictions:
    - Reads N_train from the training CSV in config_model.
    - Reads N_test from the test CSV referenced in the pkl.
    - Scales all predictions by N_test / N_train.
    - Recomputes confusion matrix, per-class/subject metrics, and scalar
      regression metrics from the scaled predictions.
    - Appends model name and scale constant to every plot title.
  Without --scale_predictions:
    - Uses pre-computed metrics from the pkl directly.
    - Appends only the model name to every plot title.
  """
  args     = parse_args()
  pkl_path = os.path.abspath(args.pkl)
  data     = load_pkl(pkl_path)
  results  = data['results']

  out_dir = os.path.join(os.path.dirname(pkl_path), 'logs_plot')
  os.makedirs(out_dir, exist_ok=True)
  print(f'Output directory: {out_dir}')

  model_name      = get_model_name(data)
  class_labels    = get_class_labels(data)
  subject_labels  = get_subject_labels(results)
  unique_subjects = [int(v) for v in results['test_unique_subject_ids']]
  n_classes       = len(class_labels)

  # --- Pass 1: original predictions (always) ---
  print('Generating original plots...')
  _run_all_plots(
    results, data, class_labels, subject_labels,
    cm=get_confusion_matrix(results),
    out_dir=out_dir,
    title_suffix=f'\n{model_name}',
    filename_suffix='',
  )

  # --- Pass 2: scaled predictions (only when --scale_predictions) ---
  if args.scale_predictions:
    scale     = compute_scale_factor(data)
    sample_df = build_sample_df(data, results)
    scaled    = recompute_scaled(sample_df, scale, n_classes, unique_subjects)

    # Merge scaled metrics into a results-compatible dict
    plot_results = {**results, **{
      k: scaled[k] for k in (
        'dict_precision_recall',
        'test_l1_error', 'test_rmse', 'test_pearson_correlation',
        'test_CCC', 'test_ICC', 'test_accuracy', 'test_macro_precision',
        'test_loss', 'test_loss_per_class', 'test_loss_per_subject',
        'test_accuracy_per_class', 'test_accuracy_per_subject',
      )
    }}

    print(f'Predictions scaled by ×{scale:.4f}')
    print('Generating scaled plots...')
    _run_all_plots(
      plot_results, data, class_labels, subject_labels,
      cm=scaled['cm'],
      out_dir=out_dir,
      title_suffix=f'\n{model_name}  |  scale ×{scale:.2f}',
      filename_suffix='_scaled',
      preds_arr=scaled['_preds_arr'],
      trues_arr=scaled['_trues_arr'],
    )

  saved = sorted(os.listdir(out_dir))
  print(f'\nDone. {len(saved)} files in {out_dir}:')
  for f in saved:
    print(f'  {f}')


if __name__ == '__main__':
  main()
