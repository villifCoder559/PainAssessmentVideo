def plot_prediction_scatter(
  data: dict,
  results: dict,
  out_dir: str,
  ax: plt.Axes = None,
  title_suffix: str = '',
  filename_suffix: str = '',
  preds_arr: np.ndarray = None,
  trues_arr: np.ndarray = None,
) -> plt.Figure:
  """
  Scatter plot of model-predicted values vs. ground-truth class labels.

  By default reads predictions from history_test_sample_predictions and
  ground truth from the CSV. When preds_arr / trues_arr are provided
  (e.g. after scaling), those arrays are used directly.

  Args:
    data:            Full pkl dictionary (used to locate the CSV when
                     preds_arr / trues_arr are not provided).
    results:         Results dictionary from the pkl.
    out_dir:         Directory for saving the individual PNG (used when ax=None).
    ax:              Optional axes to draw into (dashboard mode).
    title_suffix:    String appended to the title.
    filename_suffix: String appended before .png (e.g. '_scaled').
    preds_arr:       Optional pre-computed predictions. Shape: (N,).
                     If provided, trues_arr must also be provided.
    trues_arr:       Optional pre-computed ground-truth values. Shape: (N,).

  Returns:
    The matplotlib Figure containing the plot.
  """
  if preds_arr is not None and trues_arr is not None:
    preds = np.array(preds_arr, dtype=float)
    trues = np.array(trues_arr, dtype=float)
  else:
    gt_map = get_gt_map(data)
    hist   = results['history_test_sample_predictions']
    preds, trues = [], []
    for sid in sorted(hist.keys()):
      pred = hist[sid][0]
      if isinstance(pred, torch.Tensor):
        pred = pred.item()
      true_val = gt_map.get(int(sid))
      if true_val is not None:
        preds.append(float(pred))
        trues.append(float(true_val))
    preds = np.array(preds)
    trues = np.array(trues)

  standalone = ax is None
  if standalone:
    fig, ax = plt.subplots(figsize=(5.5, 5.5))
  else:
    fig = ax.figure

  ax.scatter(
    trues, preds,
    alpha=0.55, s=25,
    color='#4C72B0', edgecolors='white', linewidths=0.3,
  )

  lo = min(trues.min(), preds.min()) - 0.5
  hi = max(trues.max(), preds.max()) + 0.5
  ax.plot([lo, hi], [lo, hi], 'r--', linewidth=1.2, label='y = x')
  ax.set_xlim(lo, hi)
  ax.set_ylim(lo, hi)

  ax.set_title('Predicted vs. Ground Truth' + title_suffix, fontsize=11, fontweight='bold')
  ax.set_xlabel('True Class', fontsize=9)
  ax.set_ylabel('Predicted Value', fontsize=9)
  ax.legend(fontsize=8)
  ax.grid(alpha=0.3)

  if standalone:
    fig.tight_layout()
    _save_fig(fig, os.path.join(out_dir, f'prediction_scatter{filename_suffix}.png'))
  return fig


def plot_prediction_histogram(
  data: dict,
  results: dict,
  out_dir: str,
  ax: plt.Axes = None,
  title_suffix: str = '',
  filename_suffix: str = '',
  preds_arr: np.ndarray = None,
) -> plt.Figure:
  """
  Histogram of model prediction values with a KDE overlay.

  Bins use step 0.1 over the union of [csv_lo, csv_hi] and
  [preds.min(), preds.max()], so out-of-range predictions are always
  visible. Bars inside the CSV class_id range are blue; bars outside
  are orange. Two dotted vertical lines mark csv_lo and csv_hi when
  the CSV is available.

  Args:
    data:            Full pkl dictionary (used to locate the CSV for range).
    results:         Results dictionary from the pkl.
    out_dir:         Directory for saving the individual PNG (used when ax=None).
    ax:              Optional axes to draw into (dashboard mode).
    title_suffix:    String appended to the title.
    filename_suffix: String appended before .png (e.g. '_scaled').
    preds_arr:       Optional pre-computed predictions. Shape: (N,).
                     If None, extracted from history_test_sample_predictions.

  Returns:
    The matplotlib Figure containing the plot.
  """
  if preds_arr is not None:
    preds = np.array(preds_arr, dtype=float)
  else:
    hist_data = results['history_test_sample_predictions']
    preds = []
    for sid in sorted(hist_data.keys()):
      pred = hist_data[sid][0]
      if isinstance(pred, torch.Tensor):
        pred = pred.item()
      preds.append(float(pred))
    preds = np.array(preds)

  csv_lo, csv_hi = _get_csv_class_range(data)
  has_csv_range  = csv_lo is not None

  pred_lo = float(preds.min())
  pred_hi = float(preds.max())

  if has_csv_range:
    lo = min(csv_lo, pred_lo)
    hi = max(csv_hi, pred_hi)
  else:
    lo, hi = pred_lo, pred_hi

  step = 0.1
  bins    = np.arange(lo, hi + step, step)
  counts, edges = np.histogram(preds, bins=bins)
  centers = (edges[:-1] + edges[1:]) / 2.0

  # Per-bar colors: orange outside CSV range, blue inside
  if has_csv_range:
    bar_colors = [
      '#DD8452' if (c < csv_lo or c > csv_hi) else '#4C72B0'
      for c in centers
    ]
  else:
    bar_colors = ['#4C72B0'] * len(centers)

  standalone = ax is None
  if standalone:
    fig, ax = plt.subplots(figsize=(12, 4))
  else:
    fig = ax.figure

  # Blue (in-range) bars — single legend handle
  in_mask  = np.array([c == '#4C72B0' for c in bar_colors])
  oob_mask = ~in_mask

  ax.bar(centers[in_mask], counts[in_mask], width=step,
         color='#4C72B0', edgecolor='white', linewidth=0.6,
         alpha=0.75, label='In range')

  if oob_mask.any():
    ax.bar(centers[oob_mask], counts[oob_mask], width=step,
           color='#DD8452', edgecolor='white', linewidth=0.6,
           alpha=0.75, label='Out of range')

  # KDE overlay
  if len(preds) > 1:
    kde    = stats.gaussian_kde(preds)
    x_fine = np.linspace(lo, hi, 500)
    ax.plot(x_fine, kde(x_fine) * len(preds) * step,
            color='#C44E52', linewidth=1.8, label='KDE')

  # CSV range vertical dotted lines + value annotations
  if has_csv_range:
    for val, side in [(csv_lo, 'left'), (csv_hi, 'right')]:
      ax.axvline(val, linestyle=':', color='#555555', linewidth=1.5)
      ha = 'left' if side == 'left' else 'right'
      offset = step * 0.3 if side == 'left' else -step * 0.3
      ax.text(
        val + offset, 0.97, f'{val:g}',
        transform=ax.get_xaxis_transform(),
        ha=ha, va='top', fontsize=8, color='#555555',
      )

  ax.set_title('Prediction Distribution' + title_suffix, fontsize=11, fontweight='bold')
  ax.set_xlabel('Predicted Value', fontsize=9)
  ax.set_ylabel('Count', fontsize=9)
  ax.set_xlim(lo - step, hi + step)
  tick_start = np.floor((lo - step) / 0.5) * 0.5
  ax.set_xticks(np.arange(tick_start, hi + step + 0.5, 0.5))
  ax.tick_params(axis='x', labelsize=7)
  ax.legend(fontsize=8)
  ax.grid(axis='y', alpha=0.3)

  if standalone:
    fig.tight_layout()
    _save_fig(fig, os.path.join(out_dir, f'prediction_histogram{filename_suffix}.png'))
  return fig


def plot_metrics_summary(
  results: dict,
  out_dir: str,
  ax: plt.Axes = None,
  title_suffix: str = '',
  filename_suffix: str = '',
) -> plt.Figure:
  """
  Render a summary table of scalar regression and classification metrics.

  Reads from the results dict; works for both original and recomputed
  scaled results (same key names).

  Displays: L1 Error, RMSE, Pearson r, Pearson p-value, CCC, ICC,
  Accuracy, Macro Precision, Test Loss.

  Args:
    results:         Results dictionary (original or recomputed scaled).
    out_dir:         Directory for saving the individual PNG (used when ax=None).
    ax:              Optional axes to draw into (dashboard mode).
    title_suffix:    String appended to the title.
    filename_suffix: String appended before .png (e.g. '_scaled').

  Returns:
    The matplotlib Figure containing the plot.
  """
  pearson_r, pearson_p = results['test_pearson_correlation']

  rows = [
    ('L1 Error',        f"{float(results['test_l1_error']):.4f}"),
    ('RMSE',            f"{float(results['test_rmse']):.4f}"),
    ('Pearson r',       f"{float(pearson_r):.4f}"),
    ('Pearson p-value', f"{float(pearson_p):.2e}"),
    ('CCC',             f"{float(results['test_CCC']):.4f}"),
    ('ICC',             f"{float(results['test_ICC']):.4f}"),
    ('Accuracy',        f"{float(results['test_accuracy']):.4f}"),
    ('Macro Precision', f"{float(results['test_macro_precision']):.4f}"),
    ('Test Loss',       f"{float(results['test_loss']):.4f}"),
  ]

  standalone = ax is None
  if standalone:
    fig, ax = plt.subplots(figsize=(4.5, 4.5))
  else:
    fig = ax.figure

  ax.axis('off')

  tbl = ax.table(
    cellText=[[name, val] for name, val in rows],
    colLabels=['Metric', 'Value'],
    loc='center',
    cellLoc='center',
  )
  tbl.auto_set_font_size(False)
  tbl.set_fontsize(9)
  tbl.scale(1.3, 1.7)

  # Header style
  for col in range(2):
    cell = tbl[(0, col)]
    cell.set_facecolor('#4C72B0')
    cell.set_text_props(color='white', fontweight='bold')

  # Alternating row colors
  for row in range(1, len(rows) + 1):
    bg = '#eef2ff' if row % 2 == 0 else 'white'
    for col in range(2):
      tbl[(row, col)].set_facecolor(bg)

  ax.set_title('Metrics Summary' + title_suffix, fontsize=11, fontweight='bold', pad=8)

  if standalone:
    fig.tight_layout()
    _save_fig(fig, os.path.join(out_dir, f'metrics_summary{filename_suffix}.png'))
  return fig


