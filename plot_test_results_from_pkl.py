    plot_bar(
      loss_per_subject, subject_labels,
      'Loss per Subject', 'Subject ID', 'Mean Loss',
      ax=fig.add_subplot(gs[1, 1]), sort_by_value=True, color='#C44E52',
      title_suffix=title_suffix,
    )

