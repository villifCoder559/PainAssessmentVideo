def load_pkl(pkl_path: str) -> dict:
  """
  Load a pickle file.

  Args:
    pkl_path: Absolute or relative path to the .pkl file.

  Returns:
    The deserialized Python object (expected to be a dict).
  """
  with open(pkl_path, 'rb') as f:
    return pickle.load(f)


def _to_numpy(x) -> np.ndarray:
  """
  Convert a torch.Tensor or array-like to a numpy ndarray.

  Args:
    x: Input tensor, ndarray, or list.

  Returns:
    numpy ndarray.
  """
  if isinstance(x, torch.Tensor):
    return x.cpu().numpy()
  return np.array(x)


def _save_fig(fig: plt.Figure, out_path: str) -> None:
  """
  Save a matplotlib figure to disk and close it.

  Args:
    fig:      Matplotlib Figure to save.
    out_path: Destination file path (.png).
  """
  fig.savefig(out_path, bbox_inches='tight', dpi=150)
  plt.close(fig)


def _read_csv_safe(data: dict, keys: tuple = ('csv_path', 'csv_original_path')) -> pd.DataFrame:
  """
  Try to load a tab-separated CSV from the first available path in `keys`.

  Args:
    data: Full pkl dictionary.
    keys: Ordered tuple of pkl keys to try as CSV paths.

  Returns:
    Loaded DataFrame, or empty DataFrame if none found.
  """
  for key in keys:
    path = data.get(key)
    if path and os.path.isfile(path):
      try:
        return pd.read_csv(path, sep='\t')
      except Exception:
        pass
  return pd.DataFrame()
 

